MP2 = 1876.544
def F(E, gle):
    """Phi(>E) (cm^-2) with R in GV, E in MeV."""
    g1, R1, J2, g2, R2 = T2[gle]
    R = np.sqrt(np.asarray(E, float) * (np.asarray(E, float) + MP2)) / 1000.0
    g0 = g2 - g1; R0 = R1 if R2 is None else R1 * R2 / (R2 - R1); Rb = g0 * R0
    J1 = J2 * Rb ** (-g0) * np.exp(g0) if Rb > 0 else np.nan
    low = J1 * R ** (-g1) * np.exp(-R / R1); high = J2 * R ** (-g2) * np.exp(0 if R2 is None else -R / R2)
    return np.where(R < Rb, low, high)
def valid(gle, Emin=30, Emax=5000):
    E = np.geomspace(Emin, Emax, 400); f = F(E, gle)
    return bool(np.all(np.isfinite(f)) and np.all(f >= 0) and np.all(np.diff(f) <= 1e-9 * f[0]) and f[0] > 0)
